#!/usr/bin/env node
// Copies the ZepheniaLabs design system into Oculi. Never edit the outputs by hand:
// change the package (Decisions/decisions.json → Scripts/generate.py), then re-run
//   node tools/sync-zl-design.js ~/ZepheniaLabs/Workspace/Packages/ZLDesignSystem
// Outputs: css/zl-tokens.css, css/zl-tint.css, js/zl-field.js, assets/fonts/*.woff2, assets/fonts/IBM-Plex-OFL.txt
const fs = require("node:fs");
const path = require("node:path");

const pkg = process.argv[2];
if (!pkg || !fs.existsSync(path.join(pkg, "Generated/tokens.css"))) {
  console.error("usage: node tools/sync-zl-design.js <path to ZLDesignSystem>");
  process.exit(1);
}
const root = path.resolve(__dirname, "..");
const out = rel => path.join(root, rel);

// 1. Tokens, verbatim.
fs.copyFileSync(path.join(pkg, "Generated/tokens.css"), out("css/zl-tokens.css"));

// 2. The glyph-field engine: the generated bundle's constants and Field, without React.
const bundle = fs.readFileSync(path.join(pkg, "ClaudeDesign/components/bundle.js"), "utf8");
const start = bundle.indexOf("  var D = ");
const end = bundle.indexOf("  var MOTTO_LABEL");
if (start < 0 || end < 0) throw new Error("bundle.js layout changed; update tools/sync-zl-design.js");
const digest = (fs.readFileSync(path.join(pkg, "Generated/tokens.css"), "utf8").match(/Source digest (\w+)/) || [])[1] || "unknown";
const engine = `// Generated by tools/sync-zl-design.js from ZLDesignSystem/ClaudeDesign/components/bundle.js. Do not edit.
// Source digest ${digest}. The website's glyph-field engine, without React.
(function () {
  "use strict";
${bundle.slice(start, end).trimEnd()}

  var MOTTO_LABEL = "The ZepheniaLabs emblem, drawn in the letters of the motto De L\\u2019existence a L\\u2019existant";

  // The vector emblem as an SVG string, at least the vector floor tall.
  function markSvg(height, label) {
    var hgt = Math.max(D.mark.vectorFloor, height || 48);
    var a = label ? ' role="img" aria-label="' + label + '"' : ' aria-hidden="true"';
    return '<svg viewBox="0 0 ' + MW + " " + MH + '" height="' + hgt + '" width="' + (hgt * MW / MH).toFixed(2) + '"' + a + ' focusable="false"><g fill="currentColor">' +
      D.mark.paths.map(function (d) { return '<path d="' + d + '"/>'; }).join("") + "</g></svg>";
  }

  window.ZLField = Object.freeze({ D: D, Field: Field, markSvg: markSvg, MOTTO_LABEL: MOTTO_LABEL, PALETTES: D.palettes, DEFAULT_PALETTE: D.defaultPalette });
})();
`;
fs.writeFileSync(out("js/zl-field.js"), engine);

// 2b. Oculi's tint (a sanctioned exception to canon, Nov 2026): the palette's accent tints the
// working screens instead of the system blue. Light: white on the accent. Dark: the palette's
// dark ground on the accent. Both hold 4.5 : 1 or better in every palette.
const tokens = JSON.parse(fs.readFileSync(path.join(pkg, "ClaudeDesign/tokens.json"), "utf8"));
const value = name => tokens.color.tokens.find(t => t.name === name).value;
const accent = value("zl-accent"), ground = value("zl-ground");
const ids = tokens.color.themes.map(t => t.id.replace(/-(dark|light)$/, "")).filter((v, i, a) => a.indexOf(v) === i);
const sel = id => id === "zephyr" ? ":root" : `:root[data-palette="${id}"]`;
const rule = (id, mode, indent = "") => `${indent}${sel(id)} { --tint: ${accent[`${id}-${mode}`]}; --on-tint: ${mode === "light" ? "#FFFFFF" : ground[`${id}-dark`]}; --tint-light: ${accent[`${id}-light`]}; }`;
fs.writeFileSync(out("css/zl-tint.css"), `/* Generated by tools/sync-zl-design.js from ZLDesignSystem/ClaudeDesign/tokens.json. Do not edit. */
/* Oculi's tint: the viewer's palette accent, following the system appearance. Load after app.css. */
${ids.map(id => rule(id, "light")).join("\n")}
@media (prefers-color-scheme: dark) {
${ids.map(id => rule(id, "dark", "  ")).join("\n")}
}
`);

// 3. Fonts and their licence.
fs.mkdirSync(out("assets/fonts"), { recursive: true });
for (const f of fs.readdirSync(path.join(pkg, "ClaudeDesign/fonts")).filter(f => f.endsWith(".woff2"))) {
  fs.copyFileSync(path.join(pkg, "ClaudeDesign/fonts", f), out(`assets/fonts/${f}`));
}
fs.copyFileSync(path.join(pkg, "ClaudeDesign/licences/IBM-Plex-OFL.txt"), out("assets/fonts/IBM-Plex-OFL.txt"));
console.log(`Synced ZLDesignSystem ${digest.slice(0, 12)} into Oculi.`);
